/* course.js — which IB course the reader is studying: AA SL, AA HL, AI SL or AI HL.
   Loaded on every page after courses.js (generated by scripts/build.mjs).
   The choice is remembered in localStorage; ?course=<id> in the URL picks one.

   - Fills every #course-bar placeholder with the course tabs. Only the home page has one (#14);
     every other page keeps the remembered course and names it in the header.
   - On static pages, shows only elements whose data-course lists the current course
     (space-separated ids), and shows [data-course-empty] when nothing matched.
   - The search app re-renders through QB_COURSE.onChange.
*/
(function () {
  'use strict';

  const KEY = 'qb-course';
  const COURSES = window.QB_COURSES || [];
  const ids = COURSES.map(c => c.id);
  const DEFAULT = 'aa-sl';
  const listeners = [];

  function store(id) {
    try { localStorage.setItem(KEY, id); } catch (_) {}
  }

  function initial() {
    const fromUrl = new URLSearchParams(location.search).get('course');
    if (ids.includes(fromUrl)) { store(fromUrl); return fromUrl; }
    try {
      const saved = localStorage.getItem(KEY);
      if (ids.includes(saved)) return saved;
    } catch (_) {}
    return DEFAULT;
  }

  let current = initial();

  const api = {
    list: COURSES,
    get: () => current,
    info: (id) => COURSES.find(c => c.id === (id || current)),
    set(id) {
      if (!ids.includes(id) || id === current) return;
      current = id;
      store(id);
      const url = new URL(location.href);
      if (url.searchParams.has('course')) {
        url.searchParams.set('course', id);
        history.replaceState(null, '', url);
      }
      refresh();
      listeners.forEach(fn => fn(id));
    },
    onChange: (fn) => listeners.push(fn),
    bar: renderBar,
    matches: (el) => (el.dataset.course || '').split(/\s+/).includes(current)
  };
  window.QB_COURSE = api;

  function renderBar() {
    const nav = document.createElement('nav');
    nav.className = 'course-bar';
    nav.setAttribute('aria-label', 'Choose your course');
    for (const c of COURSES) {
      const a = document.createElement('a');
      a.className = `course-tab course-${c.subject}${c.id === current ? ' on' : ''}`;
      a.href = `?course=${c.id}`;
      a.dataset.courseId = c.id;
      if (c.id === current) a.setAttribute('aria-current', 'true');
      const strong = document.createElement('strong');
      strong.textContent = c.short;
      const name = document.createElement('span');
      name.className = 'course-tab-name';
      name.textContent = c.name;
      const count = document.createElement('span');
      count.className = 'course-tab-count';
      count.textContent = c.questions ? `${c.questions} questions` : 'Coming soon';
      a.append(strong, name, count);
      a.addEventListener('click', (e) => {
        e.preventDefault();
        api.set(c.id);
      });
      nav.append(a);
    }
    return nav;
  }

  function refresh() {
    document.querySelectorAll('#course-bar, .course-bar[data-static]').forEach(slot => {
      const bar = renderBar();
      bar.id = 'course-bar';
      bar.dataset.static = '';
      slot.replaceWith(bar);
    });
    let shown = 0;
    document.querySelectorAll('[data-course]').forEach(el => {
      const on = api.matches(el);
      el.hidden = !on;
      if (on) shown++;
    });
    document.querySelectorAll('[data-course-empty]').forEach(el => { el.hidden = shown > 0; });
    document.querySelectorAll('[data-course-name]').forEach(el => { el.textContent = api.info().short; });
    document.querySelectorAll('[data-course-titles]').forEach(el => {
      const title = JSON.parse(el.dataset.courseTitles)[current];
      if (!title) return;
      el.textContent = title;
      document.querySelectorAll('[data-appearance]').forEach(b => b.classList.toggle('also', b.dataset.appearance !== current));
    });
    const booklet = document.querySelector('[data-formula-booklet]');
    if (booklet) {
      const href = api.info()?.formulaBooklet;
      booklet.hidden = !href;
      if (href) booklet.href = (document.body.dataset.base || '') + href;
    }
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', refresh);
  else refresh();
})();
