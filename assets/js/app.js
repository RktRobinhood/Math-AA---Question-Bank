  // Everything here is derived from the filtered questions on each render.
  //   exam      one paper set a candidate sits: year + session + time zone (Paper 1, 2 and 3 together)
  //   marks     exact, from the per-part tags: a part's marks are shared between its subtopics
  //   weighting "Count recent years more" multiplies each exam by exp(1.5 × how recent its year is)
  function computeAnalytics(questions) {
    const years = [...new Set(questions.map(q => q.year))].sort((a, b) => a - b);
    const weight = year => {
      if (!state.recent || years.length < 2) return 1;
      return Math.exp(1.5 * (year - years[0]) / (years[years.length - 1] - years[0]));
    };
    const exams = new Map();      // exam -> weight
    const sessions = new Map();   // "2024 May" -> order
    for (const q of questions) { exams.set(q.exam, weight(q.year)); sessions.set(q.sitting, q.when); }
    const examWeight = [...exams.values()].reduce((a, b) => a + b, 0) || 1;
    const sessionList = [...sessions].sort((a, b) => a[1] - b[1]).map(s => s[0]);

    const rows = new Map(statements.map(s => [s.code, {
      code: s.code, title: s.title, topic: s.topic, exams: new Set(), questions: 0, marks: 0, wMarks: 0,
      papers: new Map(), last: -1, lastLabel: "", bySession: new Map(),
    }]));
    const topicCounts = new Map(), paperCounts = new Map(), sectionCounts = new Map();
    let totalMarks = 0;

    for (const q of questions) {
      totalMarks += q.marks;
      bump(paperCounts, q.paper, 1);
      if (q.section) bump(sectionCounts, q.section, 1);
      for (const t of q.topicNumbers || []) bump(topicCounts, t, 1);   // once per question per topic

      const share = new Map();
      const tagged = (q.parts || []).filter(p => p.syllabus?.length);
      if (tagged.length) for (const p of tagged) for (const s of p.syllabus) bump(share, codeOf(s), p.marks / p.syllabus.length);
      else for (const c of q.codes) bump(share, c, q.marks / q.codes.length);

      for (const c of q.codes) {
        const r = rows.get(c);
        if (!r) continue;
        r.exams.add(q.exam);
        r.questions += 1;
        r.marks += share.get(c) || 0;
        r.wMarks += (share.get(c) || 0) * weight(q.year);
        bump(r.papers, q.paper, 1);
        bump(r.bySession, q.sitting, 1);
        if (q.when > r.last) { r.last = q.when; r.lastLabel = `${q.session} ${q.year}`; }
      }
    }
    const list = [...rows.values()];
    for (const r of list) {
      r.examCount = r.exams.size;
      r.mpe = r.wMarks / examWeight;
      r.share = totalMarks ? r.marks / totalMarks : 0;
    }
    // Subtopics absent from the two most recent sessions in view.
    const cutoff = sessionList.length > 2 ? sessions.get(sessionList[sessionList.length - 2]) : -1;
    const notRecent = list.filter(r => r.questions && r.last < cutoff).sort((a, b) => a.last - b.last);
    return { rows: list, exams: exams.size, years, sessionList, sessions, totalMarks, topicCounts, paperCounts, sectionCounts, notRecent };
  }

